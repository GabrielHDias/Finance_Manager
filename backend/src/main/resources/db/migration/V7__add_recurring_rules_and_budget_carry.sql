ALTER TABLE monthly_budgets
    ADD COLUMN repeats_monthly BOOLEAN NOT NULL DEFAULT FALSE;

CREATE TABLE budget_month_skips (
    category_id BIGINT NOT NULL REFERENCES categories (id) ON DELETE CASCADE,
    period_start DATE NOT NULL,
    PRIMARY KEY (category_id, period_start)
);

CREATE TABLE recurring_rules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL REFERENCES accounts (id),
    category_id BIGINT NOT NULL REFERENCES categories (id),
    description VARCHAR(255) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    type VARCHAR(20) NOT NULL,
    frequency VARCHAR(20) NOT NULL,
    day_of_month INT,
    start_date DATE NOT NULL,
    end_date DATE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT chk_recurring_amount CHECK (amount > 0),
    CONSTRAINT chk_recurring_type CHECK (type IN ('INCOME', 'EXPENSE')),
    CONSTRAINT chk_recurring_frequency CHECK (frequency IN ('WEEKLY', 'MONTHLY')),
    CONSTRAINT chk_recurring_day CHECK (day_of_month IS NULL OR day_of_month BETWEEN 1 AND 31),
    CONSTRAINT chk_recurring_period CHECK (end_date IS NULL OR end_date >= start_date)
);

CREATE TABLE recurring_occurrences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id BIGINT NOT NULL REFERENCES recurring_rules (id) ON DELETE CASCADE,
    occurrence_date DATE NOT NULL,
    transaction_id BIGINT REFERENCES transactions (id) ON DELETE SET NULL,
    CONSTRAINT uk_recurring_occurrence UNIQUE (rule_id, occurrence_date)
);
